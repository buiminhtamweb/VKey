pub fn convert(input: &str, charset: Charset) -> String {
    match charset {
        Charset::Unicode => input.to_owned(),
        Charset::Tcvn3 => {
            let mut output = String::with_capacity(input.len());
            for c in input.chars() {
                if let Some(idx) = UNI_CHARS.iter().position(|&x| x == c) {
                    output.push(TCVN_CHARS[idx]);
                } else {
                    output.push(c);
                }
            }
            output
        }
        Charset::Vni => {
            let mut output = String::with_capacity(input.len());
            for c in input.chars() {
                if let Some(&(_, vni_str)) = UNI_VNI_MAP.iter().find(|&&(u, _)| u == c) {
                    output.push_str(vni_str);
                } else {
                    output.push(c);
                }
            }
            output
        }
    }
}
